def _links(urls):
    out = []
    for u in urls:
        host = urlparse(u).netloc
        out.append({"shop": SHOP_NAMES.get(host, host), "url": u})
    return out


# Imported products are listed Korean first, then American, then Japanese.
_ORIGIN_ORDER = {"Korean": 0, "American": 1, "Japanese": 2}


def recommend(skin_type, origin, category=""):
    """origin: 'local' or 'imported'. Returns a list of product dicts."""
    out = []
    for name, brand, org, cat, skin, why, urls in _ITEMS:
        is_local = org == "Local"
        if origin == "local" and not is_local:
            continue
        if origin == "imported" and is_local:
            continue
        if skin_type and "All" not in skin and skin_type not in skin:
            continue
        if category and cat.lower() != category.lower():
            continue
        out.append({
            "name": name,
            "brand": brand,
            "origin": org,
            "category": cat,
            "why": why,
            "links": _links(urls),
        })
    # Stable sort: keeps the hand-picked order inside each country.
    out.sort(key=lambda p: _ORIGIN_ORDER.get(p["origin"], 3))
    return out